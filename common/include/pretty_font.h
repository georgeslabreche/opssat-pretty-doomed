inline const Glyph& get_glyph(char c) {
    if (c >= 'A' && c <= 'Z') return GLYPHS[1 + (c - 'A')];
    if (c >= 'a' && c <= 'z') return GLYPHS[1 + (c - 'a')];
    if (c >= '0' && c <= '9') return GLYPHS[27 + (c - '0')];
    if (c == '.') return GLYPHS[37];
    if (c == ',') return GLYPHS[38];
    if (c == ':') return GLYPHS[39];
    if (c == '-') return GLYPHS[40];
    if (c == '|') return GLYPHS[41];
    if (c == '"') return GLYPHS[42];
    if (c == '!') return GLYPHS[43];
    if (c == '=') return GLYPHS[44];
    if (c == '%') return GLYPHS[45];
    if (c == '\'') return GLYPHS[46];
    if (c == '(') return GLYPHS[47];
    if (c == ')') return GLYPHS[48];
    if (c == '/') return GLYPHS[49];
    return GLYPHS[0]; // space
}

// Draw text onto an RGB pixel buffer.
// pixels: flat array of RGB triplets, row-major, (0,0) at top-left.
// scale: pixel multiplier for each glyph pixel (1 = 5x7, 2 = 10x14, etc.)
inline void draw_text(std::vector<uint8_t>& pixels, int img_w, int img_h,
                      int x, int y, const std::string& text,
                      uint8_t r, uint8_t g, uint8_t b, int scale = 1) {
    int cx = x;
    for (char c : text) {
        const Glyph& gl = get_glyph(c);
        for (int gy = 0; gy < GLYPH_H; gy++) {
            for (int gx = 0; gx < GLYPH_W; gx++) {
                if (gl.rows[gy] & (0x10 >> gx)) {
                    for (int sy = 0; sy < scale; sy++) {
                        for (int sx = 0; sx < scale; sx++) {
                            int px = cx + gx * scale + sx;
                            int py = y + gy * scale + sy;
                            if (px >= 0 && px < img_w && py >= 0 && py < img_h) {
                                int idx = (py * img_w + px) * 3;
                                pixels[idx] = r;
                                pixels[idx + 1] = g;
                                pixels[idx + 2] = b;
                            }
                        }
                    }
                }
            }
        }
        cx += (GLYPH_W + 1) * scale; // 1 pixel gap between chars
    }
}

// Measure text width in pixels
inline int text_width(const std::string& text, int scale = 1) {
    if (text.empty()) return 0;
    return (int)text.size() * (GLYPH_W + 1) * scale - scale;
}

// Draw text with a dark background box for contrast on busy images.
inline void draw_text_bg(std::vector<uint8_t>& pixels, int img_w, int img_h,
                         int x, int y, const std::string& text,
                         uint8_t r, uint8_t g, uint8_t b, int scale = 1,
                         uint8_t bg_r = 0, uint8_t bg_g = 0, uint8_t bg_b = 0) {
    int tw = text_width(text, scale);
    int th = GLYPH_H * scale;
    int pad = scale;
    for (int py = y - pad; py < y + th + pad; py++) {
        for (int px = x - pad; px < x + tw + pad; px++) {
            if (px >= 0 && px < img_w && py >= 0 && py < img_h) {
                int idx = (py * img_w + px) * 3;
                pixels[idx] = bg_r; pixels[idx + 1] = bg_g; pixels[idx + 2] = bg_b;
            }
        }
    }
    draw_text(pixels, img_w, img_h, x, y, text, r, g, b, scale);
}

// Format a float with fixed decimal places (avoids <sstream> dependency)
inline std::string fmt_float(float val, int decimals = 0) {
    char buf[32];
    if (decimals == 0)
        std::snprintf(buf, sizeof(buf), "%.0f", val);
    else if (decimals == 1)
        std::snprintf(buf, sizeof(buf), "%.1f", val);
    else
        std::snprintf(buf, sizeof(buf), "%.2f", val);
    return buf;
}

