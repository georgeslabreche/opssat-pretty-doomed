#!/usr/bin/env bash
# Window length sweep for Parakeet 0.6B v2 (issue #142).
#
# The peak memory of Parakeet 0.6B v2 grows with the window length, and the EM
# has about 990 MB free. This sweep records the effect of the window length on
# the scores, so that the window choice for the EM is visible.
#
# Usage (from tools/distress, after fetch_models.sh and prepare_clips.sh):
#   ./window_sweep.sh
# Output: results/window-sweep/w<seconds>/ (transcribe.py and score.py output)
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
py="${PYTHON:-$here/.venv/bin/python}"
for w in 5 10 15 30; do
    out="$here/results/window-sweep/w$w"
    "$py" "$here/transcribe.py" --models parakeet-0.6b-v2-int8 --window "$w" --out "$out"
    python3 "$here/score.py" --results "$out" > /dev/null
done
python3 - "$here/results/window-sweep" <<'PY'
import csv, os, sys
root = sys.argv[1]
rows = []
for w in sorted(os.listdir(root), key=lambda d: float(d[1:]) if d[1:].replace(".", "").isdigit() else 0):
    path = os.path.join(root, w, "summary.tsv")
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            r = next(csv.DictReader(f, delimiter="\t"))
        rows.append(f"| {w[1:]} | {r['recall_ship']} | {r['mayday_ship']} | {r['wer_ship']} | {r['wer_all']} | {r['peak_rss_mb']} |")
lines = ["# Window length sweep, Parakeet 0.6B v2", "",
         "Generated by `window_sweep.sh`. The peak memory is for the Python process on the ground machine.", "",
         "| Window (s) | Recall, ship-side | Mayday, ship-side | WER, ship-side | WER, all turns | Peak memory (MB) |",
         "|---|---|---|---|---|---|"] + rows + [""]
with open(os.path.join(root, "SWEEP.md"), "w", encoding="utf-8") as f:
    f.write("\n".join(lines))
print("\n".join(lines))
PY
